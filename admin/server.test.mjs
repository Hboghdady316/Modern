import test from 'node:test';
import http from 'node:http';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createAdminServer } from './server.mjs';
import { validateContent } from './validation.mjs';
const original = JSON.parse(await readFile(new URL('../vanilla-site/data/content.json', import.meta.url), 'utf8'));
test('current content validates, unsafe URLs and duplicate IDs are rejected', () => {
    assert.equal(validateContent(structuredClone(original)).schemaVersion, 1);
    const bad = structuredClone(original);
    bad.categories[0].projects[0].image = 'javascript:alert(1)';
    assert.throws(() => validateContent(bad), /HTTP/);
    const duplicate = structuredClone(original);
    duplicate.categories[0].projects.push(duplicate.categories[0].projects[0]);
    assert.throws(() => validateContent(duplicate), /unique/);
    const invalid = structuredClone(original);
    invalid.categories[0].image = '../assets/../../secret';
    assert.throws(() => validateContent(invalid), /HTTP/);
});
test('admin saves persist, recover backups, handle conflicts and reject unauthorized writes', async (t) => {
    const root = await mkdtemp(path.join(tmpdir(), 'galaxy-admin-test-'));
    await mkdir(path.join(root, 'vanilla-site/data'), { recursive: true });
    await mkdir(path.join(root, 'admin'), { recursive: true });
    await writeFile(path.join(root, 'admin/index.html'), '<h1>Local admin</h1>');
    const file = path.join(root, 'vanilla-site/data/content.json');
    await writeFile(file, JSON.stringify(original));
    const server = createAdminServer(root);
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
    t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(root, { recursive: true, force: true }); });
    const origin = `http://127.0.0.1:${server.address().port}`;
    const session = await fetch(origin + '/api/session').then(r => r.json());
    const call = (route, options = {}) => fetch(origin + route, { ...options, headers: { 'X-Admin-Token': session.token, ...options.headers } });
    const current = await call('/api/content').then(r => r.json());
    assert.equal(current.content.profile.name, original.profile.name);
    assert.equal((await fetch(origin + '/api/content', { method: 'PUT', body: '{}' })).status, 403);
    assert.equal((await call('/api/content', { method: 'PUT', headers: { Origin: 'https://evil.example' }, body: '{}' })).status, 403);
    const badHostStatus = await new Promise((resolve, reject) => { const request = http.get(origin + '/api/session', { headers: { Host: 'evil.example' } }, response => { response.resume(); resolve(response.statusCode); }); request.on('error', reject); });
    assert.equal(badHostStatus, 403);
    assert.equal((await call('/admin/server.mjs')).status, 404);
    const bad = structuredClone(original);
    bad.profile.resumeUrl = 'javascript:alert(1)';
    assert.equal((await call('/api/content', { method: 'PUT', headers: { 'Content-Type': 'application/json', 'If-Match': current.revision }, body: JSON.stringify(bad) })).status, 400);
    const changed = structuredClone(original);
    changed.profile.tagline = 'Persisted test tagline';
    const options = { method: 'PUT', headers: { 'Content-Type': 'application/json', 'If-Match': current.revision }, body: JSON.stringify(changed) };
    const results = await Promise.all([call('/api/content', options), call('/api/content', options)]);
    assert.deepEqual(results.map(r => r.status).sort(), [200, 409]);
    assert.equal(JSON.parse(await readFile(file, 'utf8')).profile.tagline, 'Persisted test tagline');
    assert.equal((await fetch(origin + '/data/content.json').then(r => r.json())).profile.tagline, 'Persisted test tagline');
    const backups = await call('/api/backups').then(r => r.json());
    assert.equal(backups.backups.length, 1);
    const backup = await call('/api/backups/' + backups.backups[0]).then(r => r.json());
    assert.equal(backup.content.profile.tagline, original.profile.tagline);
    assert.equal((await call('/admin/.backups/' + backups.backups[0])).status, 404);
    assert.equal((await call('/api/uploads', { method: 'POST', headers: { 'Content-Type': 'text/html' }, body: '<script>bad</script>' })).status, 400);
    const gif = Buffer.from('R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7', 'base64');
    const upload = await call('/api/uploads', { method: 'POST', headers: { 'Content-Type': 'image/gif' }, body: gif });
    assert.equal(upload.status, 201);
    const asset = await upload.json();
    assert.match(asset.path, /^assets\/uploads\/[a-f0-9-]+\.gif$/);
    const served = await fetch(origin + '/' + asset.path);
    assert.equal(served.headers.get('content-type'), 'image/gif');
    assert.deepEqual(Buffer.from(await served.arrayBuffer()), gif);
});
